#!/usr/bin/env python3
"""Turn the compiled jyutping lexicon into a Rime dictionary.

The engine in Sources/ ranks with word frequency plus a character bigram; Rime
has its own model, so what carries over is the lexicon itself and the weights
that came out of `build_lexicon.py`.

Rime wants one syllable per code position, so `nei5hou2` becomes `nei5 hou2`.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TSV = ROOT / "Resources" / "jyutping.tsv"
OUT = ROOT / "rime" / "cantainput.dict.yaml"

# Weight scale: librime adds these up per candidate and compares them with
# essay-frequency-like magnitudes, so keep the numbers in the same ballpark.
SCALE = 100

# Same priors the Swift engine applies (Sources/CantainputCore/Lexicon.swift).
# Without them the highest-weight entry for `dik1` is 的, which is a Mandarin
# frequency artefact: a Cantonese typist almost never means it.
CANTONESE_CHARS = set("哋唔咗喺啲佢乜嘅嚟嗰咁嘢冇睇攞諗傾瞓掟嘞喇囉喎咩咪噉㗎嗌靚攰撳揸唞嚿喐㩒嘅")
WRITTEN_CHARS = set("說與於如或並卻僅曾已將被麼這那之其乃")


def prior(text: str) -> float:
    score = 0.0
    if any(ch in CANTONESE_CHARS for ch in text):
        score += 600.0
    hits = 0
    for ch in text:
        if ch in WRITTEN_CHARS:
            hits += 1
            if hits >= 2:
                break
    return score - 200.0 * hits


def split_toned(code: str) -> list[str]:
    """Split `nei5hou2` into `['nei5', 'hou2']` on the tone digits."""
    out, cur = [], ""
    for ch in code:
        cur += ch
        if ch.isdigit():
            out.append(cur)
            cur = ""
    if cur:
        out.append(cur)
    return out


def main() -> int:
    if not TSV.exists():
        print(f"missing {TSV}; run tools/fetch_data.sh && tools/build_lexicon.py", file=sys.stderr)
        return 1

    best: dict[tuple[str, str], float] = {}
    for line in TSV.read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) < 4:
            continue
        _toneless, toned, text, score = parts[0], parts[1], parts[2], parts[3]
        if not text or not toned:
            continue
        code = " ".join(split_toned(toned))
        key = (text, code)
        try:
            value = float(score)
        except ValueError:
            continue
        value += prior(text)
        if key not in best or value > best[key]:
            best[key] = value

    rows = sorted(best.items(), key=lambda kv: -kv[1])
    print(f"{len(rows):,} entries from {TSV.name}", file=sys.stderr)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        f.write(
            "# Rime dictionary\n"
            "# encoding: utf-8\n"
            "#\n"
            "# cantainput - 粵拼詞庫（由 Sources/ 用嘅同一個詞庫編出來）\n"
            "#\n"
            "# Generated by tools/build_rime_dict.py — do not edit by hand.\n"
            "# Source: rime-cantonese (CC BY 4.0), frequencies from rime-essay\n"
            "\n"
            "---\n"
            "name: cantainput\n"
            'version: "0.1"\n'
            "sort: by_weight\n"
            "columns:\n"
            "  - text\n"
            "  - code\n"
            "  - weight\n"
            "...\n"
            "\n"
        )
        for (text, code), score in rows:
            weight = max(1, int(score * SCALE))
            f.write(f"{text}\t{code}\t{weight}\n")

    print(f"wrote {OUT} {OUT.stat().st_size/1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
